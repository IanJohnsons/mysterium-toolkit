#!/bin/bash
# Mysterium Node Toolkit — privileged helper (v1.4.60)
#
# Every change the toolkit makes as root goes through this one script, with a
# closed list of actions. Each action validates its arguments and builds any file
# it writes itself: the caller passes names and numbers, never file content, a
# path outside the list below, or a command line.
#
# Why: the sudoers entry used to grant /bin/bash, /bin/cat, `tee` on wildcard
# paths and `systemctl … mysterium-*`. A `*` in a sudoers argument also matches
# "/", ".." and spaces, so `tee /etc/sysctl.d/*` wrote anywhere and
# `systemctl start mysterium-*` started any unit. Together that was passwordless
# root for the toolkit user. This helper is what the sudoers entry will name
# instead (v1.4.61 removes the old grants; v1.4.60 adds this alongside them).
#
# Installed by setup.sh / update.sh as root to
#   /usr/local/lib/mysterium-toolkit/toolkit-helper   (root:root 0755)
# The copy in the repository is not the one sudo runs: a file the toolkit user
# can edit must never be what sudo executes.
#
# Exit codes: 0 done · 64 refused (unknown action or invalid argument) ·
# 65 not run as root · anything else is the exit code of the command it ran.

set -u
umask 022
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
export LC_ALL=C

EX_REFUSED=64
ACTION="${1:-}"
[ $# -gt 0 ] && shift

log() { command -v logger >/dev/null 2>&1 && logger -t mysterium-toolkit-helper -- "$*" 2>/dev/null; return 0; }
refuse() { echo "refused: $*" >&2; log "refused: $ACTION — $*"; exit "$EX_REFUSED"; }
done_rc() { local rc=$1; log "$ACTION $ARGS_FOR_LOG → rc=$rc"; exit "$rc"; }
ARGS_FOR_LOG="$*"

if [ "$(id -u)" -ne 0 ]; then
    echo "toolkit-helper must run as root (through sudo)" >&2
    exit 65
fi

# ── Validators ────────────────────────────────────────────────────────────────
is_uint()  { [[ "$1" =~ ^[0-9]{1,12}$ ]]; }
is_iface() { [[ "$1" =~ ^[A-Za-z0-9_][A-Za-z0-9_.:-]{0,14}$ ]] && [[ "$1" != *..* ]]; }
in_list()  { local v="$1"; shift; local x; for x in "$@"; do [ "$x" = "$v" ] && return 0; done; return 1; }

SYSCTL_PERSIST_FILE=/etc/sysctl.d/99-mysterium-node.conf
RPS_SCRIPT_FILE=/usr/local/bin/mysterium-rps-setup.sh
RPS_SERVICE_NAME=mysterium-rps-tuning
RPS_SERVICE_FILE=/etc/systemd/system/mysterium-rps-tuning.service
GOVERNORS=(performance powersave ondemand conservative schedutil userspace)

# Keys the toolkit tunes or has ever persisted. Values: one to three numbers,
# except the two named settings below.
SYSCTL_KEYS=(
    net.ipv4.ip_forward net.core.rmem_max net.core.wmem_max net.core.rmem_default
    net.core.wmem_default net.core.netdev_max_backlog net.core.somaxconn
    net.ipv4.tcp_max_syn_backlog net.ipv4.tcp_tw_reuse net.ipv4.tcp_slow_start_after_idle
    net.ipv4.udp_rmem_min net.ipv4.udp_wmem_min net.netfilter.nf_conntrack_max
    net.ipv4.tcp_congestion_control net.core.default_qdisc vm.swappiness
    net.ipv4.tcp_rmem net.ipv4.tcp_wmem net.ipv4.udp_mem
)
valid_sysctl() {   # key value
    in_list "$1" "${SYSCTL_KEYS[@]}" || return 1
    case "$1" in
        net.ipv4.tcp_congestion_control) in_list "$2" bbr cubic reno ;;
        net.core.default_qdisc)          in_list "$2" fq fq_codel pfifo_fast cake ;;
        *) [[ "$2" =~ ^[0-9]{1,12}([[:space:]]+[0-9]{1,12}){0,2}$ ]] ;;
    esac
}

# Writes stdin to $1 through a temporary file in the same directory, then
# renames it over the target. $2 is the mode for a new file; an existing file
# keeps its own mode and owner. A reader never sees a half-written file.
atomic_write() {
    local target="$1" mode="$2" dir tmp
    dir="$(dirname "$target")"
    [ -d "$dir" ] || return 1
    tmp="$(mktemp "$dir/.toolkit-helper.XXXXXX")" || return 1
    if ! cat > "$tmp"; then rm -f "$tmp"; return 1; fi
    if [ -e "$target" ]; then
        chmod --reference="$target" "$tmp" 2>/dev/null || chmod "$mode" "$tmp"
        chown --reference="$target" "$tmp" 2>/dev/null || chown root:root "$tmp"
    else
        chmod "$mode" "$tmp"; chown root:root "$tmp"
    fi
    mv -f "$tmp" "$target" || { rm -f "$tmp"; return 1; }
}

# Prints the key = value lines of the sysctl persist file as "key<TAB>value".
sysctl_file_pairs() {
    [ -f "$SYSCTL_PERSIST_FILE" ] || return 0
    awk -F= '/^[[:space:]]*#/ {next} /=/ {
        k=$1; sub(/^[[:space:]]+/, "", k); sub(/[[:space:]]+$/, "", k)
        v=substr($0, index($0, "=")+1); sub(/^[[:space:]]+/, "", v); sub(/[[:space:]]+$/, "", v)
        if (k != "") print k "\t" v }' "$SYSCTL_PERSIST_FILE"
}

sysctl_header() {
    printf '# Mysterium Node Toolkit — persisted network tuning\n'
    printf '# Generated by %s. Remove with unpersist or recovery.sh\n' "$1"
    printf '# Created: %s\n\n' "$(date -Iseconds)"
}

case "$ACTION" in

# ── Kernel parameters ────────────────────────────────────────────────────────
sysctl-set)                              # KEY VALUE
    [ $# -eq 2 ] || refuse "usage: sysctl-set KEY VALUE"
    valid_sysctl "$1" "$2" || refuse "sysctl key or value not allowed: $1=$2"
    sysctl -w "$1=$2" >/dev/null; done_rc $? ;;

sysctl-reload)
    [ $# -eq 0 ] || refuse "usage: sysctl-reload"
    sysctl --system >/dev/null; done_rc $? ;;

# Replace the whole persist file with these pairs (persist_all).
sysctl-persist-replace)                  # KEY=VALUE...
    [ $# -ge 1 ] || refuse "usage: sysctl-persist-replace KEY=VALUE..."
    for kv in "$@"; do valid_sysctl "${kv%%=*}" "${kv#*=}" || refuse "not allowed: $kv"; done
    { sysctl_header "--health-persist"
      for kv in "$@"; do printf '%s = %s\n' "${kv%%=*}" "${kv#*=}"; done
    } | atomic_write "$SYSCTL_PERSIST_FILE" 0644; done_rc $? ;;

# Merge these pairs into the persist file, sorted by key (persist_one).
sysctl-persist-set)                      # KEY=VALUE...
    [ $# -ge 1 ] || refuse "usage: sysctl-persist-set KEY=VALUE..."
    for kv in "$@"; do valid_sysctl "${kv%%=*}" "${kv#*=}" || refuse "not allowed: $kv"; done
    {
        sysctl_header "persist_one"
        { sysctl_file_pairs
          for kv in "$@"; do printf '%s\t%s\n' "${kv%%=*}" "${kv#*=}"; done
        } | awk -F'\t' '{ v[$1]=$2 } END { for (k in v) print k " = " v[k] }' | sort
    } | atomic_write "$SYSCTL_PERSIST_FILE" 0644; done_rc $? ;;

# Drop these keys from the persist file; remove the file when nothing is left.
sysctl-persist-unset)                    # KEY...
    [ $# -ge 1 ] || refuse "usage: sysctl-persist-unset KEY..."
    for k in "$@"; do in_list "$k" "${SYSCTL_KEYS[@]}" || refuse "key not allowed: $k"; done
    [ -f "$SYSCTL_PERSIST_FILE" ] || { echo "absent"; done_rc 0; }
    keys=" $* "
    new="$(awk -v keys="$keys" '{
        line=$0; t=line; sub(/^[[:space:]]+/, "", t)
        if (t != "" && substr(t,1,1) != "#" && index(t, "=") > 0) {
            k=substr(t, 1, index(t, "=")-1); sub(/[[:space:]]+$/, "", k)
            if (index(keys, " " k " ") > 0) next
        }
        print line }' "$SYSCTL_PERSIST_FILE")"
    if ! printf '%s\n' "$new" | grep -qvE '^[[:space:]]*(#|$)'; then
        rm -f "$SYSCTL_PERSIST_FILE"; rc=$?; echo "removed"; done_rc $rc
    fi
    printf '%s\n' "$new" | atomic_write "$SYSCTL_PERSIST_FILE" 0644; done_rc $? ;;

# ── /sys values ──────────────────────────────────────────────────────────────
sys-write)                               # PATH VALUE
    [ $# -eq 2 ] || refuse "usage: sys-write PATH VALUE"
    p="$1"; v="$2"
    case "$p" in
        /sys/module/nf_conntrack/parameters/hashsize) is_uint "$v" || refuse "value: $v" ;;
        /sys/devices/system/cpu/cpu*/cpufreq/scaling_governor)
            [[ "$p" =~ ^/sys/devices/system/cpu/cpu[0-9]{1,4}/cpufreq/scaling_governor$ ]] || refuse "path: $p"
            in_list "$v" "${GOVERNORS[@]}" || refuse "governor: $v" ;;
        /sys/class/net/*/queues/rx-*/rps_cpus|/sys/class/net/*/queues/rx-*/rps_flow_cnt)
            [[ "$p" =~ ^/sys/class/net/([^/]+)/queues/rx-[0-9]{1,4}/(rps_cpus|rps_flow_cnt)$ ]] || refuse "path: $p"
            dev="${BASH_REMATCH[1]}" leaf="${BASH_REMATCH[2]}"   # is_iface resets BASH_REMATCH
            is_iface "$dev" || refuse "interface: $dev"
            if [ "$leaf" = rps_cpus ]; then
                [[ "$v" =~ ^[0-9a-fA-F,]{1,64}$ ]] || refuse "mask: $v"
            else
                is_uint "$v" || refuse "value: $v"
            fi ;;
        *) refuse "path not allowed: $p" ;;
    esac
    [ -e "$p" ] || refuse "no such file: $p"
    printf '%s\n' "$v" > "$p"; done_rc $? ;;

# ── Modules ──────────────────────────────────────────────────────────────────
modprobe)                                # MODULE
    [ $# -eq 1 ] && in_list "$1" tcp_bbr nf_conntrack || refuse "module not allowed: ${1:-}"
    modprobe -- "$1"; done_rc $? ;;

module-persist)                          # MODULE — load at boot
    [ $# -eq 1 ] && in_list "$1" tcp_bbr nf_conntrack || refuse "module not allowed: ${1:-}"
    if [ -d /etc/modules-load.d ]; then
        printf '%s\n' "$1" | atomic_write "/etc/modules-load.d/$1.conf" 0644; done_rc $?
    fi
    grep -qx "$1" /etc/modules 2>/dev/null && done_rc 0
    printf '%s\n' "$1" >> /etc/modules; done_rc $? ;;

module-unpersist)                        # MODULE
    [ $# -eq 1 ] && in_list "$1" tcp_bbr nf_conntrack || refuse "module not allowed: ${1:-}"
    rm -f "/etc/modules-load.d/$1.conf"
    if [ -f /etc/modules ] && grep -qx "$1" /etc/modules; then
        grep -vx "$1" /etc/modules | atomic_write /etc/modules 0644; done_rc $?
    fi
    done_rc 0 ;;

# ── Network interface ────────────────────────────────────────────────────────
ethtool-coalesce)                        # IFACE PARAM VALUE [PARAM VALUE]...
    [ $# -ge 3 ] && [ $(( ($# - 1) % 2 )) -eq 0 ] || refuse "usage: ethtool-coalesce IFACE PARAM VALUE..."
    is_iface "$1" || refuse "interface: $1"
    iface="$1"; shift; argv=()
    while [ $# -gt 0 ]; do
        case "$1" in
            rx-usecs|tx-usecs) is_uint "$2" && [ "$2" -le 100000 ] || refuse "value: $1 $2" ;;
            adaptive-rx|adaptive-tx) in_list "$2" on off || refuse "value: $1 $2" ;;
            *) refuse "parameter not allowed: $1" ;;
        esac
        argv+=("$1" "$2"); shift 2
    done
    ethtool -C "$iface" "${argv[@]}"; done_rc $? ;;

ethtool-rxcsum)                          # IFACE on|off
    [ $# -eq 2 ] && is_iface "$1" && in_list "$2" on off || refuse "usage: ethtool-rxcsum IFACE on|off"
    ethtool -K "$1" rx "$2"; done_rc $? ;;

governor-set)                            # GOVERNOR
    [ $# -eq 1 ] && in_list "$1" "${GOVERNORS[@]}" || refuse "governor not allowed: ${1:-}"
    cpupower frequency-set -g "$1" >/dev/null; done_rc $? ;;

# Boot script for NIC coalescing + RPS, as persist_one has written it since
# before v1.4.40. Built here; only the interface and two numbers come in.
rps-persist)                             # IFACE MASK RX_USECS
    [ $# -eq 3 ] || refuse "usage: rps-persist IFACE MASK RX_USECS"
    is_iface "$1" || refuse "interface: $1"
    [[ "$2" =~ ^[0-9a-fA-F]{1,64}$ ]] || refuse "mask: $2"
    is_uint "$3" && [ "$3" -le 100000 ] || refuse "rx-usecs: $3"
    printf '%s\n' \
        '#!/bin/bash' \
        '# Mysterium Node Toolkit — NIC + RPS tuning (runs at boot)' \
        "MASK=\"$2\"" \
        "IFACE=\"$1\"" \
        "ethtool -C \"\$IFACE\" rx-usecs $3 2>/dev/null" \
        'for q in /sys/class/net/$IFACE/queues/rx-*/rps_cpus; do' \
        '    echo "$MASK" > "$q" 2>/dev/null' \
        'done' \
        'exit 0' | atomic_write "$RPS_SCRIPT_FILE" 0755 || done_rc 1
    chmod 755 "$RPS_SCRIPT_FILE"
    if [ ! -f "$RPS_SERVICE_FILE" ]; then
        printf '%s\n' \
            '[Unit]' \
            'Description=Mysterium Node NIC + RPS Tuning' \
            'After=network-online.target' \
            'Wants=network-online.target' \
            '[Service]' \
            'Type=oneshot' \
            "ExecStart=$RPS_SCRIPT_FILE" \
            'RemainAfterExit=yes' \
            '[Install]' \
            'WantedBy=multi-user.target' | atomic_write "$RPS_SERVICE_FILE" 0644 || done_rc 1
    fi
    done_rc 0 ;;

rps-csum-persist)                        # IFACE — keep rx checksumming off at boot
    [ $# -eq 1 ] && is_iface "$1" || refuse "usage: rps-csum-persist IFACE"
    line="ethtool -K \"$1\" rx off 2>/dev/null"
    if [ -f "$RPS_SCRIPT_FILE" ]; then
        grep -q 'ethtool -K' "$RPS_SCRIPT_FILE" && { echo "present"; done_rc 0; }
        { sed -e '$a\' "$RPS_SCRIPT_FILE"; printf '%s\n' "$line"; } | atomic_write "$RPS_SCRIPT_FILE" 0755
        done_rc $?
    fi
    printf '%s\n' '#!/bin/bash' "$line" | atomic_write "$RPS_SCRIPT_FILE" 0755; done_rc $? ;;

rps-csum-unpersist)
    [ $# -eq 0 ] || refuse "usage: rps-csum-unpersist"
    [ -f "$RPS_SCRIPT_FILE" ] || { echo "absent"; done_rc 0; }
    sed '/ethtool -K.*rx off/d' "$RPS_SCRIPT_FILE" | atomic_write "$RPS_SCRIPT_FILE" 0755; done_rc $? ;;

# ── Files the toolkit created ────────────────────────────────────────────────
remove)                                  # PATH — only files the toolkit writes
    [ $# -eq 1 ] || refuse "usage: remove PATH"
    case "$1" in
        "$SYSCTL_PERSIST_FILE"|"$RPS_SCRIPT_FILE"|"$RPS_SERVICE_FILE"|\
        /usr/local/bin/mysterium-rps-watcher.sh|\
        /etc/systemd/system/mysterium-rps-watcher.service|\
        /etc/systemd/system/mysterium-rps-watcher.timer|\
        /usr/local/bin/mysterium-cpu-governor.sh|\
        /etc/systemd/system/mysterium-cpu-governor.service|\
        /etc/default/cpupower|/etc/default/cpufrequtils|\
        /etc/local.d/myst-governor.start|\
        /etc/modules-load.d/tcp_bbr.conf|/etc/modules-load.d/nf_conntrack.conf) ;;
        /etc/fail2ban/jail.d/mysterium-toolkit.conf)
            # Pre-v1.4.18 jail file: only when it still carries the toolkit header.
            [ -f "$1" ] && ! head -c 200 "$1" | grep -q 'Mysterium Toolkit — managed jail file' \
                && refuse "no toolkit header in $1 — left in place" ;;
        *) refuse "path not allowed: $1" ;;
    esac
    rm -f -- "$1"; done_rc $? ;;

fstab-drop-swapfile)                     # remove the /swapfile line, leave swap running
    [ $# -eq 0 ] || refuse "usage: fstab-drop-swapfile"
    grep -qF /swapfile /etc/fstab 2>/dev/null || { echo "absent"; done_rc 0; }
    grep -vF /swapfile /etc/fstab | atomic_write /etc/fstab 0644; done_rc $? ;;

# ── systemd ──────────────────────────────────────────────────────────────────
systemctl)                               # ACTION UNIT
    [ $# -eq 2 ] || refuse "usage: systemctl ACTION UNIT"
    unit="${2%.service}"
    in_list "$unit" mysterium-node irqbalance fail2ban mysterium-toolkit-update.timer \
        "$RPS_SERVICE_NAME" mysterium-rps-watcher.timer mysterium-cpu-governor \
        || refuse "unit not allowed: $2"
    case "$1" in
        start|stop|restart|enable|disable) systemctl "$1" "$unit" ;;
        enable-now)  systemctl enable --now "$unit" ;;
        disable-now) systemctl disable --now "$unit" ;;
        *) refuse "systemctl action not allowed: $1" ;;
    esac
    done_rc $? ;;

daemon-reload)
    [ $# -eq 0 ] || refuse "usage: daemon-reload"
    systemctl daemon-reload; done_rc $? ;;

# ── Packages ─────────────────────────────────────────────────────────────────
pkg-install)                             # NAME
    [ $# -eq 1 ] && in_list "$1" irqbalance ethtool conntrack conntrack-tools fail2ban \
        || refuse "package not allowed: ${1:-}"
    if   command -v apt-get >/dev/null; then DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "$1"
    elif command -v dnf     >/dev/null; then dnf install -y "$1"
    elif command -v yum     >/dev/null; then yum install -y "$1"
    elif command -v pacman  >/dev/null; then pacman -S --noconfirm "$1"
    elif command -v apk     >/dev/null; then apk add "$1"
    elif command -v zypper  >/dev/null; then zypper install -y "$1"
    else echo "no supported package manager" >&2; done_rc 127; fi
    done_rc $? ;;

# ── fail2ban — the toolkit's own jail only ───────────────────────────────────
f2b-filter-write)
    [ $# -eq 0 ] || refuse "usage: f2b-filter-write"
    [ -d /etc/fail2ban/filter.d ] || refuse "fail2ban is not installed"
    printf '%s\n' '[Definition]' 'failregex = ^.*Auth failed from <HOST>\s.*$' 'ignoreregex =' \
        | atomic_write /etc/fail2ban/filter.d/mysterium-dashboard.conf 0644; done_rc $? ;;

# none | ENABLED PORT FILTER BACKEND LOGPATH MAXRETRY BANTIME FINDTIME ("-" = not set)
f2b-jail-write)
    [ -d /etc/fail2ban/jail.d ] || refuse "fail2ban is not installed"
    jail_file=/etc/fail2ban/jail.d/zz-mysterium-toolkit.conf
    header=$'# Mysterium Toolkit — managed jail file.\n# This entire file is owned by the toolkit; edit jails via the dashboard.\n# The toolkit never touches sshd, recidive or any system jail.\n'
    if [ $# -eq 1 ] && [ "$1" = none ]; then
        printf '%s\n' "$header" | atomic_write "$jail_file" 0644; done_rc $?
    fi
    [ $# -eq 8 ] || refuse "usage: f2b-jail-write none | ENABLED PORT FILTER BACKEND LOGPATH MAXRETRY BANTIME FINDTIME"
    enabled="$1" port="$2" filter="$3" backend="$4" logpath="$5" maxretry="$6" bantime="$7" findtime="$8"
    in_list "$enabled" true false || refuse "enabled: $enabled"
    [ "$port" = - ] || [[ "$port" =~ ^[A-Za-z0-9][A-Za-z0-9,:-]{0,99}$ ]] || refuse "port: $port"
    [[ "$filter" =~ ^[A-Za-z0-9_-]{1,64}$ ]] || refuse "filter: $filter"
    in_list "$backend" auto systemd || refuse "backend: $backend"
    if [ "$logpath" != - ]; then
        [[ "$logpath" =~ ^/[A-Za-z0-9_./*-]{1,254}$ ]] || refuse "logpath: $logpath"
        [[ "/$logpath/" == */../* ]] && refuse "logpath may not contain .."
    fi
    is_uint "$maxretry" && [ "$maxretry" -ge 1 ] && [ "$maxretry" -le 1000 ] || refuse "maxretry: $maxretry"
    { [ "$bantime" = -1 ] || { is_uint "$bantime" && [ "$bantime" -ge 1 ] && [ "$bantime" -le 315360000 ]; }; } || refuse "bantime: $bantime"
    is_uint "$findtime" && [ "$findtime" -ge 1 ] && [ "$findtime" -le 315360000 ] || refuse "findtime: $findtime"
    {
        printf '%s\n' "$header"
        printf '[mysterium-dashboard]\n'
        printf 'enabled  = %s\n' "$enabled"
        [ "$port" != - ] && printf 'port     = %s\n' "$port"
        printf 'filter   = %s\n' "$filter"
        if [ "$backend" = systemd ]; then
            printf 'backend  = systemd\n'
        else
            printf 'backend  = auto\n'
            [ "$logpath" != - ] && printf 'logpath  = %s\n' "$logpath"
        fi
        printf 'maxretry = %s\nbantime  = %s\nfindtime = %s\n\n' "$maxretry" "$bantime" "$findtime"
    } | atomic_write "$jail_file" 0644; done_rc $? ;;

# Remove the block versions up to v1.4.17 wrote into jail.local. Everything
# outside the markers stays as it is.
f2b-jail-local-strip)
    [ $# -eq 0 ] || refuse "usage: f2b-jail-local-strip"
    f=/etc/fail2ban/jail.local
    start='# --- Mysterium Toolkit managed jails ---'
    end='# --- End Mysterium Toolkit ---'
    [ -f "$f" ] && grep -qxF -- "$start" "$f" && grep -qxF -- "$end" "$f" || { echo "absent"; done_rc 0; }
    awk -v s="$start" -v e="$end" '
        $0 == s { skip=1; next }
        skip && $0 == e { skip=0; next }
        !skip { print }' "$f" | awk 'NF { last=NR } { line[NR]=$0 } END {
            first=0; for (i=1; i<=last; i++) { if (!first && line[i] !~ /[^[:space:]]/) continue; first=1; print line[i] } }' \
        | atomic_write "$f" 0644; done_rc $? ;;

f2b-set)                                 # JAIL bantime|maxretry|findtime|unbanip VALUE
    [ $# -eq 3 ] || refuse "usage: f2b-set JAIL PARAM VALUE"
    [[ "$1" =~ ^[A-Za-z0-9_-]{1,64}$ ]] || refuse "jail: $1"
    case "$2" in
        bantime)  { [ "$3" = -1 ] || is_uint "$3"; } || refuse "value: $3" ;;
        maxretry|findtime) is_uint "$3" || refuse "value: $3" ;;
        unbanip)  [[ "$3" =~ ^[0-9a-fA-F.:]{2,45}$ ]] || refuse "address: $3" ;;
        *) refuse "parameter not allowed: $2" ;;
    esac
    fail2ban-client set "$1" "$2" "$3"; done_rc $? ;;

f2b)                                     # reload|start|stop
    [ $# -eq 1 ] && in_list "$1" reload start stop || refuse "usage: f2b reload|start|stop"
    fail2ban-client "$1"; done_rc $? ;;

# ── Firewall ─────────────────────────────────────────────────────────────────
# ufw: "<allow|deny|reject|limit> [from] SPEC", "delete <that>", "delete N",
# each optionally preceded by --force. No other option is passed through.
ufw)
    argv=("$@"); [ "${argv[0]:-}" = --force ] && argv=("${argv[@]:1}")
    [ "${argv[0]:-}" = delete ] && del=1 && argv=("${argv[@]:1}") || del=0
    rule="${argv[*]:-}"
    if [ "$del" = 1 ] && [[ "$rule" =~ ^[0-9]{1,5}$ ]]; then :
    elif [[ "$rule" =~ ^(allow|deny|reject|limit)\ (from\ )?[A-Za-z0-9_/:,.-]+$ ]]; then :
    else refuse "ufw rule not allowed: $*"; fi
    ufw "$@"; done_rc $? ;;

# iptables: any table operation the dashboard performs, but never --modprobe,
# which makes iptables execute a program of the caller's choosing.
ipt)                                     # BINARY ARGS...
    [ $# -ge 2 ] || refuse "usage: ipt BINARY ARGS..."
    in_list "$1" iptables iptables-legacy iptables-nft ip6tables ip6tables-legacy || refuse "binary: $1"
    bin="$1"; shift
    for a in "$@"; do
        [[ "$a" =~ ^[A-Za-z0-9_.:/,!=-]{1,64}$ ]] || refuse "argument: $a"
        [[ "$a" == --modprobe* || "$a" == -M ]] && refuse "argument: $a"
    done
    "$bin" "$@"; done_rc $? ;;

# ── Node configuration file ──────────────────────────────────────────────────
# Fallback for when `myst config set wireguard.access-policies` fails: edits the
# first node config file that exists. remove = drop the key; set VALUE = drop it
# and write it under [wireguard].
node-access-policy)                      # remove | set "" | set mysterium
    case "${1:-}:$#" in
        remove:1) value="" ;;
        set:2) in_list "$2" "" mysterium || refuse "policy not allowed: $2"; value="$2" ;;
        *) refuse "usage: node-access-policy remove | set \"\"|mysterium" ;;
    esac
    cfg=""
    for c in /etc/mysterium-node/config.toml /etc/mysterium-node/config-mainnet.toml; do
        [ -f "$c" ] && { cfg="$c"; break; }
    done
    [ -n "$cfg" ] || { echo "no node config file" >&2; done_rc 1; }
    stripped="$(sed -E 's/^[[:space:]]*access-policies[[:space:]]*=.*$//' "$cfg")"
    if [ "$1" = remove ]; then
        printf '%s\n' "$stripped" | atomic_write "$cfg" 0644; done_rc $?
    fi
    if printf '%s\n' "$stripped" | grep -qF '[wireguard]'; then
        printf '%s\n' "$stripped" | awk -v v="$value" '
            !done && index($0, "[wireguard]") { print; print "  access-policies = \"" v "\""; done=1; next } { print }' \
            | atomic_write "$cfg" 0644
    else
        { printf '%s\n' "$stripped"; printf '\n[wireguard]\n  access-policies = "%s"\n' "$value"; } \
            | atomic_write "$cfg" 0644
    fi
    done_rc $? ;;

version)
    echo "toolkit-helper 1.4.60"; exit 0 ;;

*)
    refuse "unknown action: ${ACTION:-<none>}" ;;
esac
